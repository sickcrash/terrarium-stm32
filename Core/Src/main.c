static void ConfiguraSensore(void){
	uint8_t config_data[3] = {0x02, 0x10, 0x00}; // register address + 16 bit config.
	// TEMP: Bit[10] to 0 for 14 bit resolution, Bit[10] to 1 for 11 bit resolution
	// HUM: Bit[9:8] to 00 for 14 bit resolution, Bit[9:8] to 01 for 11 bit resolution, Bit[9:8] to 10 for 8 bit resolution.
	// 0001 0000 0000 0000 = 14 bit temp, 14 bit hum

	HAL_I2C_Master_Transmit(&hi2c1, HDC1080_ADDR, config_data, 3, 100);
	HAL_Delay(100);
}

static void AvviaMisurazioneSensore(void){
	uint8_t reg_pointer = 0x00;
	HAL_I2C_Master_Transmit(&hi2c1, HDC1080_ADDR,  &reg_pointer, 1, 100);
	HAL_Delay(100);
}

static void LeggiSensore(float *temperatura, float *umidita){
	uint8_t rx_data[4];
	char uart_buffer[100];
	int len;
	if (HAL_I2C_Master_Receive(&hi2c1, HDC1080_ADDR, rx_data, 4, 100) == HAL_OK)
	{
		// il sensore riempie rx data con 2 byte di temp e 2 byte di hum
		// prendo il primo byte e con '<<8' lo rendo a due byte, poi riempio
		// l'ultimo byte di zeri ottenuto con '|' mettendo il secondo byte
		uint16_t raw_temp = (rx_data[0] << 8) | rx_data[1];
	    uint16_t raw_umid = (rx_data[2] << 8) | rx_data[3];

	    // calcoliamo i valori applicando le formule del datasheet
	    *temperatura = ((float)raw_temp / 65536.0f) * 165.0f - 40.0f;
	    *umidita = ((float)raw_umid / 65536.0f) * 100.0f;

	    len = sprintf(uart_buffer, "Temperatura: %.2f C  Umidita': %.2f %% \r\n", *temperatura, *umidita);
	    HAL_UART_Transmit(&huart1, (uint8_t*)uart_buffer, len, 100);
	 }
	 else
	 {
	    len = sprintf(uart_buffer, "Errore di lettura dal sensore.\r\n");
	    HAL_UART_Transmit(&huart1, (uint8_t*)uart_buffer, len, 100);
	 }
}

